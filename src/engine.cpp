// Low-latency matching engine, idea 1.
// Price-time priority, limit and market orders, cancels.
// Single-threaded, in-process. No network, no live trading, no real money.
// Input: CSV orders, one per line:
//   NEW,<id>,BUY|SELL,<price_cents>,<qty>
//   NEW,<id>,BUY|SELL,MARKET,<qty>
//   CANCEL,<id>
// Output: trades to stdout as CSV:
//   TRADE,<buy_id>,<sell_id>,<price_cents>,<qty>
//   BOOK,<best_bid_price>,<best_bid_qty>,<best_ask_price>,<best_ask_qty>
// Latency: --bench prints p50/p99/max and throughput for add_order,
// measured inside the process with steady_clock, not network time.
// Prices are integer cents, quantities are integer shares/units, so
// there is no floating point in the hot path.
#include <algorithm>
#include <chrono>
#include <cstdint>
#include <deque>
#include <fstream>
#include <iostream>
#include <limits>
#include <map>
#include <sstream>
#include <string>
#include <unordered_map>
#include <vector>

enum class Side { Buy, Sell };

struct Order {
    uint64_t id = 0;
    Side side = Side::Buy;
    int64_t price = 0; // cents; MARKET buy = INT64_MAX, MARKET sell = 0
    uint64_t qty = 0;
    bool is_market = false;
};

struct Trade {
    uint64_t buy_id = 0;
    uint64_t sell_id = 0;
    int64_t price = 0;
    uint64_t qty = 0;
};

class OrderBook {
public:
    // Returns trades generated by this order.
    std::vector<Trade> add_order(Order in) {
        std::vector<Trade> trades;
        if (in.side == Side::Buy) {
            while (in.qty > 0 && !asks_.empty()) {
                auto it = asks_.begin();
                int64_t ask_price = it->first;
                if (!in.is_market && ask_price > in.price) break;
                auto &q = it->second;
                Order &resting = q.front();
                uint64_t fill = std::min(in.qty, resting.qty);
                trades.push_back({in.id, resting.id, ask_price, fill});
                in.qty -= fill;
                resting.qty -= fill;
                if (resting.qty == 0) {
                    id_index_.erase(resting.id);
                    q.pop_front();
                    if (q.empty()) asks_.erase(it);
                }
            }
            if (in.qty > 0 && !in.is_market) {
                bids_[in.price].push_back(in);
                id_index_[in.id] = {Side::Buy, in.price};
            }
        } else {
            while (in.qty > 0 && !bids_.empty()) {
                auto it = bids_.begin();
                int64_t bid_price = it->first;
                if (!in.is_market && bid_price < in.price) break;
                auto &q = it->second;
                Order &resting = q.front();
                uint64_t fill = std::min(in.qty, resting.qty);
                trades.push_back({resting.id, in.id, bid_price, fill});
                in.qty -= fill;
                resting.qty -= fill;
                if (resting.qty == 0) {
                    id_index_.erase(resting.id);
                    q.pop_front();
                    if (q.empty()) bids_.erase(it);
                }
            }
            if (in.qty > 0 && !in.is_market) {
                asks_[in.price].push_back(in);
                id_index_[in.id] = {Side::Sell, in.price};
            }
        }
        return trades;
    }

    bool cancel(uint64_t id) {
        auto it = id_index_.find(id);
        if (it == id_index_.end()) return false;
        auto [side, price] = it->second;
        bool removed = false;
        if (side == Side::Buy) {
            auto bit = bids_.find(price);
            if (bit != bids_.end()) {
                auto &q = bit->second;
                for (auto qit = q.begin(); qit != q.end(); ++qit) {
                    if (qit->id == id) { q.erase(qit); removed = true; break; }
                }
                if (q.empty()) bids_.erase(bit);
            }
        } else {
            auto bit = asks_.find(price);
            if (bit != asks_.end()) {
                auto &q = bit->second;
                for (auto qit = q.begin(); qit != q.end(); ++qit) {
                    if (qit->id == id) { q.erase(qit); removed = true; break; }
                }
                if (q.empty()) asks_.erase(bit);
            }
        }
        id_index_.erase(it);
        return removed;
    }

    // best bid, best bid qty, best ask, best ask qty; -1 if a side is empty
    void best(int64_t &bp, uint64_t &bq, int64_t &ap, uint64_t &aq) const {
        bp = -1; bq = 0; ap = -1; aq = 0;
        if (!bids_.empty()) {
            bp = bids_.begin()->first;
            for (auto &o : bids_.begin()->second) bq += o.qty;
        }
        if (!asks_.empty()) {
            ap = asks_.begin()->first;
            for (auto &o : asks_.begin()->second) aq += o.qty;
        }
    }

    size_t resting_orders() const { return id_index_.size(); }

private:
    // bids: highest price first; asks: lowest price first.
    // deque per price level gives FIFO, i.e. time priority at a price.
    std::map<int64_t, std::deque<Order>, std::greater<int64_t>> bids_;
    std::map<int64_t, std::deque<Order>> asks_;
    std::unordered_map<uint64_t, std::pair<Side, int64_t>> id_index_;
};

static std::vector<std::string> split(const std::string &s, char delim) {
    std::vector<std::string> out;
    std::stringstream ss(s);
    std::string item;
    while (std::getline(ss, item, delim)) out.push_back(item);
    return out;
}

int main(int argc, char **argv) {
    std::string orders_path;
    bool bench = false;
    for (int i = 1; i < argc; i++) {
        std::string a = argv[i];
        if (a == "--orders" && i + 1 < argc) orders_path = argv[++i];
        if (a == "--bench") bench = true;
    }
    std::istream *in = &std::cin;
    std::ifstream file;
    if (!orders_path.empty()) {
        file.open(orders_path);
        if (!file) { std::cerr << "cannot open " << orders_path << "\n"; return 1; }
        in = &file;
    }

    OrderBook book;
    std::vector<int64_t> lat_ns;
    lat_ns.reserve(100000);
    std::string line;
    uint64_t orders_in = 0, trades_out = 0;
    auto t_start = std::chrono::steady_clock::now();

    while (std::getline(*in, line)) {
        if (line.empty() || line[0] == '#') continue;
        auto parts = split(line, ',');
        if (parts.empty()) continue;
        auto t0 = std::chrono::steady_clock::now();
        if (parts[0] == "NEW" && parts.size() >= 5) {
            Order o;
            o.id = std::stoull(parts[1]);
            o.side = (parts[2] == "BUY") ? Side::Buy : Side::Sell;
            if (parts[3] == "MARKET") {
                o.is_market = true;
                o.price = (o.side == Side::Buy) ? std::numeric_limits<int64_t>::max() : 0;
            } else {
                o.price = std::stoll(parts[3]);
            }
            o.qty = std::stoull(parts[4]);
            auto trades = book.add_order(o);
            orders_in++;
            for (auto &t : trades) {
                std::cout << "TRADE," << t.buy_id << "," << t.sell_id << ","
                          << t.price << "," << t.qty << "\n";
                trades_out++;
            }
        } else if (parts[0] == "CANCEL" && parts.size() >= 2) {
            book.cancel(std::stoull(parts[1]));
            orders_in++;
        }
        auto t1 = std::chrono::steady_clock::now();
        if (bench) {
            lat_ns.push_back(std::chrono::duration_cast<std::chrono::nanoseconds>(t1 - t0).count());
        }
    }
    auto t_end = std::chrono::steady_clock::now();

    int64_t bp, ap; uint64_t bq, aq;
    book.best(bp, bq, ap, aq);
    std::cout << "BOOK," << bp << "," << bq << "," << ap << "," << aq << "\n";
    std::cerr << "orders=" << orders_in << " trades=" << trades_out
              << " resting=" << book.resting_orders() << "\n";

    if (bench && !lat_ns.empty()) {
        std::sort(lat_ns.begin(), lat_ns.end());
        auto pct = [&](double p) {
            return lat_ns[static_cast<size_t>(p * (lat_ns.size() - 1))];
        };
        double secs = std::chrono::duration<double>(t_end - t_start).count();
        std::cerr << "latency_ns p50=" << pct(0.50) << " p99=" << pct(0.99)
                  << " max=" << lat_ns.back()
                  << " throughput_orders_per_sec=" << static_cast<uint64_t>(orders_in / secs)
                  << "\n";
    }
    return 0;
}
